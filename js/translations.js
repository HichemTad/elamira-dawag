var LANG_META = {
  fr: { flag: '🇫🇷', code: 'FR', dir: 'ltr', lang: 'fr' },
  en: { flag: '🇬🇧', code: 'EN', dir: 'ltr', lang: 'en' },
  ar: { flag: '🇩🇿', code: 'AR', dir: 'rtl', lang: 'ar' }
};

function applyLanguage(lang) {
  if (!TRANSLATIONS[lang]) return;
  var t = TRANSLATIONS[lang];
  var meta = LANG_META[lang];

  // Update html attributes
  document.documentElement.lang = meta.lang;
  document.documentElement.dir = meta.dir;

  // Update text content
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  // Update innerHTML (for keys with <br> etc.)
  document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) el.placeholder = t[key];
  });

  // Update page title
  document.title = lang === 'ar'
    ? 'الأميرة وداواق — عجائن حرفية استثنائية'
    : lang === 'en'
    ? 'El Amira & Dawag — Exceptional Artisan Pastries'
    : "El Amira & Dawag — Pâtes Artisanales d'Exception";

  // Update lang switcher indicator
  var flagEl = document.querySelector('.lang-current-flag');
  var codeEl = document.querySelector('.lang-current-code');
  if (flagEl) flagEl.textContent = meta.flag;
  if (codeEl) codeEl.textContent = meta.code;

  // Update active state on all lang buttons (desktop + mobile)
  document.querySelectorAll('.lang-option, .mobile-lang-option').forEach(function(btn) {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  localStorage.setItem('lang', lang);
}
